CREATE TABLE problem_state_operations (
    id BIGINT NOT NULL AUTO_INCREMENT,
    operation_id VARCHAR(100) COLLATE utf8mb4_bin NOT NULL,
    problem_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    operation_type VARCHAR(30) NOT NULL,
    idempotency_key VARCHAR(100) COLLATE utf8mb4_bin NOT NULL,
    request_hash CHAR(64) NOT NULL,
    expected_source_version INT NOT NULL,
    result_source_version INT NULL,
    before_visibility VARCHAR(30) NOT NULL,
    target_visibility VARCHAR(30) NOT NULL,
    state VARCHAR(30) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    response_status INT NULL,
    response_json JSON NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_problem_state_operations_problem FOREIGN KEY (problem_id) REFERENCES problems(id),
    CONSTRAINT uk_problem_state_operations_operation UNIQUE (operation_id),
    CONSTRAINT uk_problem_state_operations_request UNIQUE (actor_id, problem_id, operation_type, idempotency_key),
    INDEX idx_problem_state_operations_pending (state, updated_at),
    INDEX idx_problem_state_operations_version (problem_id, state, result_source_version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
