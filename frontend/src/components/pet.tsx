export function Pet({
  level = 2,
  size = 96,
  label = "알고리즘 펫",
}: {
  level?: number;
  size?: number;
  label?: string;
}) {
  const paths: Record<string, string> = {};
  sprites[Math.min(4, level)].forEach((r, y) =>
    [...r].forEach((c, x) => {
      if (c !== ".") paths[c] = (paths[c] || "") + `M${x} ${y}h1v1h-1z`;
    }),
  );
  return (
    <svg
      role="img"
      aria-label={label}
      className="pet-sprite"
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
    >
      {Object.entries(paths).map(([c, d]) => (
        <path
          key={c}
          d={d}
          fill={
            c === "+"
              ? "var(--lime)"
              : c === "m"
                ? "var(--pink)"
                : c === "*"
                  ? "var(--pink)"
                  : "var(--ink)"
          }
        />
      ))}
    </svg>
  );
}
