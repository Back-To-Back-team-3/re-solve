CREATE TABLE exam_submissions (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    exam_participant_id BIGINT NOT NULL,
    exam_id BIGINT NOT NULL,
    problem_id BIGINT NOT NULL,
    draft_seq BIGINT NOT NULL,
    language VARCHAR(30) NOT NULL,
    source_code MEDIUMTEXT NOT NULL,
    submission_type VARCHAR(30) NOT NULL,
    received_at DATETIME(6) NOT NULL,
    status VARCHAR(30) NOT NULL,
    submission_id BIGINT NULL,
    judge_attempt INT NULL,
    verdict VARCHAR(30) NULL,
    passed_count INT NULL,
    total_count INT NULL,
    score DECIMAL(6, 2) NULL,
    is_zero_confirmed BOOLEAN NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    CONSTRAINT fk_exam_submissions_participant FOREIGN KEY (exam_participant_id) REFERENCES exam_participants (id),
    CONSTRAINT fk_exam_submissions_exam FOREIGN KEY (exam_id) REFERENCES exams (id),
    CONSTRAINT uk_exam_submissions_participant_problem_seq UNIQUE (exam_participant_id, problem_id, draft_seq),
    INDEX idx_exam_submissions_exam_status (exam_id, status),
    INDEX idx_exam_submissions_status_created_at (status, created_at),
    INDEX idx_exam_submissions_submission (submission_id)
);
